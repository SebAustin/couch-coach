#!/usr/bin/env node
/**
 * Copies the shared contract code into the TV app and generates its runtime config.
 *
 *   ../../packages/protocol/src/index.ts      -> packages/shared-ui/src/vendor/protocol/index.ts
 *   ../../packages/events-client/src/**       -> packages/shared-ui/src/vendor/events-client/**
 *   ../../infra/client-config.json            -> packages/shared-ui/src/config.generated.ts
 *
 * apps/tv is a standalone Yarn workspace, so it cannot import the sibling packages by path;
 * the vendored copies are committed so a fresh clone builds without running this script.
 * Re-run it (`yarn sync`) whenever the protocol, events client, or infra config changes.
 *
 * Usage: node scripts/sync-shared.mjs [--config path/to/client-config.json] [--check]
 *   --check  exit 1 if the vendored files are out of date (for CI), write nothing.
 */
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const tvRoot = resolve(here, '..');
const repoRoot = resolve(tvRoot, '../..');
const sharedSrc = join(tvRoot, 'packages/shared-ui/src');

const args = process.argv.slice(2);
const checkOnly = args.includes('--check');
const configFlag = args.indexOf('--config');
const configPath = resolve(configFlag >= 0 ? args[configFlag + 1] : join(repoRoot, 'infra/client-config.json'));

const protocolSrc = join(repoRoot, 'packages/protocol/src/index.ts');
const eventsClientSrc = join(repoRoot, 'packages/events-client/src');
const protocolDest = join(sharedSrc, 'vendor/protocol/index.ts');
const eventsClientDest = join(sharedSrc, 'vendor/events-client');
const configDest = join(sharedSrc, 'config.generated.ts');

const HEADER = '// GENERATED by apps/tv/scripts/sync-shared.mjs. Do not edit; change the source and re-run `yarn sync`.\n';
/** Shown by the app when the real infra config was not available at sync time. */
const PLACEHOLDER_CONFIG = {
  apiBaseUrl: 'https://api.placeholder.invalid',
  eventsHttpHost: 'placeholder.appsync-api.us-east-1.amazonaws.com',
  eventsRealtimeHost: 'placeholder.appsync-realtime-api.us-east-1.amazonaws.com',
  eventsApiKey: 'da2-placeholder',
  phoneUrl: 'https://phone.placeholder.invalid',
};
const CONFIG_KEYS = Object.keys(PLACEHOLDER_CONFIG);

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    return statSync(full).isDirectory() ? walk(full) : [full];
  });
}

const sha = (text) => createHash('sha256').update(text).digest('hex');

/** Returns the planned writes as [destPath, contents] pairs (never touches disk). */
function plan() {
  const writes = [];
  if (existsSync(protocolSrc)) {
    writes.push([protocolDest, HEADER + readFileSync(protocolSrc, 'utf8')]);
  } else {
    console.warn(`! protocol not found at ${protocolSrc}; keeping the vendored copy`);
  }
  if (existsSync(eventsClientSrc)) {
    for (const file of walk(eventsClientSrc)) {
      if (!file.endsWith('.ts')) continue;
      writes.push([join(eventsClientDest, relative(eventsClientSrc, file)), HEADER + readFileSync(file, 'utf8')]);
    }
  } else {
    console.warn(`! events-client not found at ${eventsClientSrc}; keeping the vendored copy`);
  }
  writes.push([configDest, renderConfig()]);
  return writes;
}

function loadConfig() {
  if (!existsSync(configPath)) {
    console.warn(`! ${relative(process.cwd(), configPath)} not found; generating PLACEHOLDER config`);
    return { config: PLACEHOLDER_CONFIG, isPlaceholder: true };
  }
  const raw = JSON.parse(readFileSync(configPath, 'utf8'));
  const missing = CONFIG_KEYS.filter((key) => typeof raw[key] !== 'string' || raw[key] === '');
  if (missing.length > 0) {
    throw new Error(`client config ${configPath} is missing: ${missing.join(', ')}`);
  }
  return { config: Object.fromEntries(CONFIG_KEYS.map((key) => [key, raw[key]])), isPlaceholder: false };
}

function renderConfig() {
  const { config, isPlaceholder } = loadConfig();
  return (
    HEADER +
    "import type { ClientConfig } from './vendor/protocol';\n\n" +
    `export const clientConfig: ClientConfig = ${JSON.stringify(config, null, 2)};\n\n` +
    '/** True until `yarn sync` finds infra/client-config.json; the app shows a setup notice. */\n' +
    `export const isPlaceholderConfig = ${isPlaceholder};\n`
  );
}

const writes = plan();

if (checkOnly) {
  const stale = writes.filter(([dest, contents]) => !existsSync(dest) || sha(readFileSync(dest, 'utf8')) !== sha(contents));
  if (stale.length > 0) {
    console.error(`Out of date:\n${stale.map(([d]) => `  ${relative(tvRoot, d)}`).join('\n')}\nRun: yarn sync`);
    process.exit(1);
  }
  console.log('Vendored files are up to date.');
  process.exit(0);
}

// Replace the events-client vendor directory wholesale so deleted upstream files disappear.
if (existsSync(eventsClientSrc)) rmSync(eventsClientDest, { recursive: true, force: true });
for (const [dest, contents] of writes) {
  mkdirSync(dirname(dest), { recursive: true });
  writeFileSync(dest, contents);
  console.log(`  wrote ${relative(tvRoot, dest)}`);
}
